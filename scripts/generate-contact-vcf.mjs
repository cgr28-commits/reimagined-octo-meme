/**
 * Regenerate public/my-airport-taxi-ni.vcf with an embedded logo photo.
 * Uses vcards-js so the PHOTO field matches the format iOS/Android expect.
 * Also syncs a copy into the Cloudflare Worker for correct text/vcard MIME.
 *
 * Usage: node scripts/generate-contact-vcf.mjs
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const require = createRequire(import.meta.url);
const vCardsJS = require("vcards-js");

const root = process.cwd();
const photoPath = join(root, "public", "contact-photo.jpg");
const outPath = join(root, "public", "my-airport-taxi-ni.vcf");
const workerOutPath = join(root, "shared", "contact-vcard.ts");

const vCard = vCardsJS();
vCard.firstName = "My Airport Taxi NI";
vCard.organization = "My Airport Taxi NI";
vCard.title = "Airport Transfers";
vCard.workPhone = "+442896022952";
vCard.cellPhone = "+447549815538";
vCard.workEmail = "bookings@myairporttaxini.co.uk";
vCard.url = "https://www.myairporttaxini.co.uk";
vCard.note =
  "WhatsApp @belfasttaxi. Premium airport transfers across Northern Ireland";
vCard.photo.embedFromFile(photoPath);
vCard.logo.embedFromFile(photoPath);

const content = vCard.getFormattedString();
writeFileSync(outPath, content);

const workerModule =
  "/** Auto-generated by scripts/generate-contact-vcf.mjs — do not edit by hand. */\n" +
  `export const CONTACT_VCARD = ${JSON.stringify(content)};\n`;
writeFileSync(workerOutPath, workerModule);

console.log(`Wrote ${outPath} (${content.length} bytes)`);
console.log(`Wrote ${workerOutPath}`);
