/**
 * Regenerate public/my-airport-taxi-ni.vcf with an iOS-safe embedded logo.
 *
 * Notes for iPhone:
 * - PHOTO only (no LOGO) — dual image fields confuse some importers
 * - TYPE=JPEG with ENCODING=b
 * - PHOTO placed near the top after the name fields
 *
 * Usage: node scripts/generate-contact-vcf.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const photoPath = join(root, "public", "contact-photo.jpg");
const outPath = join(root, "public", "my-airport-taxi-ni.vcf");
const sharedOutPath = join(root, "shared", "contact-vcard.ts");

const photo = readFileSync(photoPath);
const b64 = photo.toString("base64");

function foldLine(line) {
  const max = 75;
  const bytes = Buffer.from(line, "utf8");
  if (bytes.length <= max) return [line];

  const out = [];
  let start = 0;
  let first = true;
  while (start < bytes.length) {
    const budget = first ? max : max - 1;
    let end = Math.min(start + budget, bytes.length);
    while (end > start && (bytes[end] & 0xc0) === 0x80) end -= 1;
    if (end === start) end = Math.min(start + budget, bytes.length);
    const chunk = bytes.subarray(start, end).toString("utf8");
    out.push(first ? chunk : ` ${chunk}`);
    first = false;
    start = end;
  }
  return out;
}

function photoProperty(base64) {
  // Keep value on the header line (vcards-js / many iOS samples do this), then fold.
  return foldLine(`PHOTO;ENCODING=b;TYPE=JPEG:${base64}`);
}

const lines = [
  "BEGIN:VCARD",
  "VERSION:3.0",
  "PRODID:-//Apple Inc.//iPhone OS 18.0//EN",
  "FN:My Airport Taxi NI",
  "N:;My Airport Taxi NI;;;",
  "ORG:My Airport Taxi NI;",
  "TITLE:Airport Transfers",
  ...photoProperty(b64),
  "TEL;type=WORK;type=VOICE;type=pref:+442896022952",
  "TEL;type=CELL;type=VOICE:+447549815538",
  "EMAIL;type=INTERNET;type=WORK;type=pref:bookings@myairporttaxini.co.uk",
  "URL;type=pref:https://www.myairporttaxini.co.uk",
  "NOTE:WhatsApp @belfasttaxi. Premium airport transfers across Northern Ireland",
  "END:VCARD",
];

const content = `${lines.join("\r\n")}\r\n`;
writeFileSync(outPath, content);

const sharedModule =
  "/** Auto-generated by scripts/generate-contact-vcf.mjs — do not edit by hand. */\n" +
  `export const CONTACT_VCARD = ${JSON.stringify(content)};\n`;
writeFileSync(sharedOutPath, sharedModule);

console.log(`Wrote ${outPath} (${content.length} bytes, photo ${photo.length} bytes)`);
console.log(`Wrote ${sharedOutPath}`);
