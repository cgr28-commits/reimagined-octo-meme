/**
 * Regenerate public/my-airport-taxi-ni.vcf with an iOS-safe embedded logo.
 *
 * Notes for iPhone:
 * - PHOTO only (no LOGO) — dual image fields confuse some importers
 * - TYPE=JPEG with ENCODING=b
 * - X-ABCROP-RECTANGLE covers the full square so Contacts does not
 *   auto-zoom onto the car icon and strip the wordmark / green band
 * - Rebuild contact-photo.jpg first: python3 scripts/create-contact-photo.py
 *
 * Usage: node scripts/generate-contact-vcf.mjs
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const photoPath = join(root, "public", "contact-photo.jpg");
const outPath = join(root, "public", "my-airport-taxi-ni.vcf");
const sharedOutPath = join(root, "shared", "contact-vcard.ts");

const photo = readFileSync(photoPath);
const b64 = photo.toString("base64");

/** Read JPEG SOF dimensions (baseline / progressive). */
function jpegSize(buf) {
  let i = 2;
  while (i < buf.length - 8) {
    if (buf[i] !== 0xff) {
      i += 1;
      continue;
    }
    const marker = buf[i + 1];
    if (marker === 0xc0 || marker === 0xc2) {
      const height = buf.readUInt16BE(i + 5);
      const width = buf.readUInt16BE(i + 7);
      return { width, height };
    }
    if (marker === 0xd8 || marker === 0xd9) {
      i += 2;
      continue;
    }
    const len = buf.readUInt16BE(i + 2);
    i += 2 + len;
  }
  return { width: 720, height: 720 };
}

function foldLine(line) {
  const max = 75;
  const bytes = Buffer.from(line, "utf8");
  if (bytes.length <= max) return [line];

  const out = [];
  let start = 0;
  let first = true;
  while (start < bytes.length) {
    const budget = first ? max : max - 1;
    let end = Math.min(start + budget, bytes.length);
    while (end > start && (bytes[end] & 0xc0) === 0x80) end -= 1;
    if (end === start) end = Math.min(start + budget, bytes.length);
    const chunk = bytes.subarray(start, end).toString("utf8");
    out.push(first ? chunk : ` ${chunk}`);
    first = false;
    start = end;
  }
  return out;
}

function photoProperty(photoBuf, base64) {
  const { width, height } = jpegSize(photoBuf);
  // Apple crop: x, y-from-bottom, width, height, base64(md5(image bytes))
  const digest = createHash("md5").update(photoBuf).digest("base64");
  const crop = `ABClipRect_1&0&0&${width}&${height}&${digest}`;
  return foldLine(
    `PHOTO;ENCODING=b;TYPE=JPEG;X-ABCROP-RECTANGLE=${crop}:${base64}`,
  );
}

const lines = [
  "BEGIN:VCARD",
  "VERSION:3.0",
  "PRODID:-//My Airport Taxi NI//Contact Card//EN",
  "FN:My Airport Taxi NI",
  "N:;My Airport Taxi NI;;;",
  "ORG:My Airport Taxi NI",
  "TITLE:Belfast & Northern Ireland Airport Transfers",
  ...photoProperty(photo, b64),
  // Public business line only — no personal/mobile numbers in the vCard.
  "TEL;TYPE=WORK,VOICE:+442896022952",
  "EMAIL;TYPE=WORK:bookings@myairporttaxini.co.uk",
  "URL:https://www.myairporttaxini.co.uk",
  "NOTE:Belfast & Northern Ireland Airport Transfers",
  "END:VCARD",
];

const content = `${lines.join("\r\n")}\r\n`;
writeFileSync(outPath, content);

// Canonical download filename used in emails and Content-Disposition.
const aliasOutPath = join(root, "public", "My-Airport-Taxi-NI.vcf");
writeFileSync(aliasOutPath, content);

const sharedModule =
  "/** Auto-generated by scripts/generate-contact-vcf.mjs — do not edit by hand. */\n" +
  `export const CONTACT_VCARD = ${JSON.stringify(content)};\n` +
  `export const CONTACT_VCARD_FILENAME = "My-Airport-Taxi-NI.vcf";\n`;
writeFileSync(sharedOutPath, sharedModule);

const { width, height } = jpegSize(photo);
console.log(
  `Wrote ${outPath} and ${aliasOutPath} (${content.length} bytes, photo ${photo.length} bytes, ${width}x${height}, full ABCROP)`,
);
console.log(`Wrote ${sharedOutPath}`);
