/**
 * Writes shared/whatsapp-knowledge.ts — the website's FAQs, terms, privacy and service
 * details as one text block, so the Worker's WhatsApp assistant answers from the same
 * source as the site. Re-run after changing FAQs/terms:
 *   npx tsx scripts/generate-whatsapp-knowledge.ts        (write)
 *   npx tsx scripts/generate-whatsapp-knowledge.ts --check (fail if stale)
 */
import fs from "node:fs";
import path from "node:path";
import { getAssistantKnowledgeChunks } from "../src/lib/quote-assistant";

// Website-chat-only flow descriptions; the WhatsApp assistant has its own flow.
const SKIP = new Set(["How booking works", "Quote tool flow"]);

// Route landing pages ("Belfast to Dublin Airport Taxi") repeat the FAQs at length.
const isRoutePage = (title: string) => /\bto\b.*\b(airport|taxi|transfer)/i.test(title) || /\btaxi\b/i.test(title);

const text = getAssistantKnowledgeChunks()
  .filter((c) => !SKIP.has(c.title) && !isRoutePage(c.title))
  .map((c) => `## ${c.title}\n${c.body.trim()}`)
  .join("\n\n");

const out =
  "// Generated by scripts/generate-whatsapp-knowledge.ts — do not edit by hand.\n" +
  `export const WHATSAPP_KNOWLEDGE = ${JSON.stringify(text)};\n`;

const target = path.resolve(import.meta.dirname, "../shared/whatsapp-knowledge.ts");
if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== out) {
    console.error("shared/whatsapp-knowledge.ts is stale — run: npx tsx scripts/generate-whatsapp-knowledge.ts");
    process.exit(1);
  }
  console.log("WhatsApp knowledge is up to date.");
} else {
  fs.writeFileSync(target, out);
  console.log(`Wrote ${target} (${text.length} chars)`);
}
